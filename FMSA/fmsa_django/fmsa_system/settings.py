def _adopt_sqlite_name(directory: Path, new_name: str, old_name: str) -> Path:
    """新库不存在而旧库 mtws_*.db 还在时，启动前改成 fmsa_*.db，避免配置和告警数据落空。"""
    new_path = directory / new_name
    old_path = directory / old_name
    if new_path.exists() or not old_path.exists():
        return new_path
    directory.mkdir(parents=True, exist_ok=True)
    try:
        for suffix in ('', '-wal', '-shm'):
            src = directory / f'{old_name}{suffix}'
            dst = directory / f'{new_name}{suffix}'
            if src.exists() and not dst.exists():
                src.rename(dst)
    except OSError:
        if old_path.exists() and not new_path.exists():
            return old_path
    return directory / new_name


